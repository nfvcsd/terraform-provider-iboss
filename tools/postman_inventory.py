#!/usr/bin/env python3
"""Fetch the public iboss Postman collection and inventory its operations.

This reads *documentation* only. It never sends requests to an iboss tenant.

Usage:
  python3 tools/postman_inventory.py fetch --out build/postman/iboss.json
  python3 tools/postman_inventory.py inventory build/postman/iboss.json \
      --out docs/api-inventory.md

`fetch` prints the SHA-256 of the downloaded body; record it with the
retrieval date in docs/api-coverage.md. `inventory` writes a Markdown table
of every documented operation (folder, name, method, host, path, query keys,
source link) so coverage gaps stay visible in review.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import urllib.request
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any, Iterator

COLLECTION_URL = (
    "https://documenter.gw.postman.com/api/collections/26524233/2s93RUuXjk"
    "?segregateAuth=true&versionTag=latest"
)
DOC_URL = "https://documenter.getpostman.com/view/26524233/2s93RUuXjk"
HOST_LABELS = {
    "{{baseApiDomain}}": "core",
    "{{gatewayNodeApiDomain}}": "gateway",
    "{{reportingNodeApiDomain}}": "reporting",
    "{{browserIsolationNodeApiDomain}}": "browser-isolation",
    "{{ibossAccounts}}": "accounts",
}


@dataclass(frozen=True)
class Operation:
    folder: str
    name: str
    method: str
    host: str
    path: str
    query: tuple[str, ...]
    item_id: str

    @property
    def link(self) -> str:
        return f"{DOC_URL}#{self.item_id}" if self.item_id else DOC_URL


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _url_parts(request: dict[str, Any]) -> tuple[str, str, tuple[str, ...]]:
    url = request.get("urlObject") or request.get("url") or {}
    if isinstance(url, str):
        # Collection v2 allows a raw string URL; split it conservatively.
        raw = url.split("://", 1)[-1]
        host, _, rest = raw.partition("/")
        path, _, query = rest.partition("?")
        keys = tuple(p.split("=", 1)[0] for p in query.split("&") if p)
        return HOST_LABELS.get(host, host), "/" + path, keys
    host = ".".join(url.get("host") or [])
    path = "/" + "/".join(url.get("path") or [])
    keys = tuple(q.get("key", "") for q in url.get("query") or [])
    return HOST_LABELS.get(host, host), path, keys


def walk(items: list[dict[str, Any]], folder: tuple[str, ...] = ()) -> Iterator[Operation]:
    for item in items:
        if "item" in item:
            yield from walk(item["item"], folder + (item.get("name", ""),))
            continue
        request = item.get("request") or {}
        host, path, query = _url_parts(request)
        yield Operation(
            folder=" / ".join(folder) or "(root)",
            name=item.get("name", ""),
            method=request.get("method", ""),
            host=host,
            path=path,
            query=query,
            item_id=item.get("id", ""),
        )


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(collection: dict[str, Any], digest: str, retrieved: str) -> str:
    ops = list(walk(collection.get("item", [])))
    info = collection.get("info", {})
    lines = [
        "# iboss API operation inventory",
        "",
        "Generated by `tools/postman_inventory.py`; do not edit by hand.",
        "",
        f"- Collection: {info.get('name', '')} (`{info.get('_postman_id', '')}`)",
        f"- Source: {DOC_URL}",
        f"- Retrieved: {retrieved}",
        f"- SHA-256 of retrieved JSON: `{digest}`",
        f"- Operations: {len(ops)}",
        "",
        "| Folder | Operation | Method | Host | Path | Query keys |",
        "|---|---|---|---|---|---|",
    ]
    for op in ops:
        lines.append(
            "| {f} | [{n}]({l}) | {m} | {h} | `{p}` | {q} |".format(
                f=_cell(op.folder), n=_cell(op.name), l=op.link, m=op.method,
                h=_cell(op.host), p=_cell(op.path), q=_cell(", ".join(op.query)),
            )
        )
    return "\n".join(lines) + "\n"


def cmd_fetch(args: argparse.Namespace) -> int:
    with urllib.request.urlopen(args.url, timeout=60) as resp:  # noqa: S310 (fixed https URL)
        data = resp.read()
    json.loads(data)  # fail loudly if the body is not JSON
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(data)
    print(f"{sha256(data)}  {out}")
    return 0


def cmd_inventory(args: argparse.Namespace) -> int:
    data = Path(args.collection).read_bytes()
    digest = sha256(data)
    if args.expect_sha256 and args.expect_sha256 != digest:
        print(f"digest mismatch: expected {args.expect_sha256}, got {digest}", file=sys.stderr)
        return 1
    text = render(json.loads(data), digest, args.retrieved or date.today().isoformat())
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fetch", help="download the published collection JSON")
    f.add_argument("--url", default=COLLECTION_URL)
    f.add_argument("--out", required=True)
    f.set_defaults(func=cmd_fetch)
    i = sub.add_parser("inventory", help="render a Markdown operation inventory")
    i.add_argument("collection")
    i.add_argument("--out")
    i.add_argument("--retrieved", help="retrieval date (YYYY-MM-DD); defaults to today")
    i.add_argument("--expect-sha256", help="fail unless the file has this digest")
    i.set_defaults(func=cmd_inventory)
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
